package X;
public class operators {

    public static void main(String[] args) {

        int x = 5;
        int y = 3;

        System.out.print("The value of x: ");
        System.out.println(x);

        System.out.print("The value of y: ");
        System.out.println(y);

        System.out.print("The value of x and y: ");
        System.out.println(x + " and " + y);

        System.out.println("The value of x and y: " + 5 + " and " + 3);

        System.out.print("The value of x % y: ");
        System.out.println(x % y);

        System.out.print("The value of x + y: ");
        System.out.println(x + y);

        System.out.print("The value of x - y: ");
        System.out.println(x - y);

        System.out.print("The value of x * y: ");
        System.out.println(x * y);

        System.out.print("The value of x / y: ");
        System.out.println(x / y);

        float w = 5f;
        float z = 3f;

        System.out.print("The value of w / z : ");
        System.out.println(w / z);

        int a = 7;

        System.out.println(a++);
        System.out.println(a--);
        System.out.println(++a);
        System.out.println(--a);

    }

}
